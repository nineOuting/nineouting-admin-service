package com.nineouting.backend.admin;

import static org.assertj.core.api.Assertions.assertThat;
import static org.hamcrest.Matchers.contains;
import static org.hamcrest.Matchers.hasItem;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.delete;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.put;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.header;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import com.nineouting.backend.admin.auth.AuthInterceptor;
import com.nineouting.backend.admin.auth.LoginGuard;
import jakarta.servlet.http.Cookie;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.http.MediaType;
import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.request.MockHttpServletRequestBuilder;
import org.testcontainers.postgresql.PostgreSQLContainer;

/** 실제 PostgreSQL에 붙어 로그인, 표 탐색, 한 행 추가, 수정, 삭제와 막아야 할 요청을 시험한다 */
@SpringBootTest
@AutoConfigureMockMvc
class AdminApiTest {

    private static final String USERNAME = "tester";
    private static final String PASSWORD = "test-password";
    static final PostgreSQLContainer POSTGRES = new PostgreSQLContainer("postgres:17.6-alpine");

    @Autowired
    MockMvc mockMvc;

    @Autowired
    LoginGuard guard;

    static {
        POSTGRES.start();
        createTables();
    }

    private static void createTables() {
        try (Connection connection = DriverManager.getConnection(POSTGRES.getJdbcUrl(), POSTGRES.getUsername(),
                POSTGRES.getPassword()); Statement sql = connection.createStatement()) {
            sql.execute("""
                    create table items (
                      id bigint generated by default as identity primary key,
                      name varchar(50) not null unique,
                      data jsonb,
                      tags text[],
                      created_at timestamp not null default now(),
                      password_hash varchar(100)
                    );
                    create table pairs (a int, b varchar(10), note text, primary key (a, b));
                    create table logs (message text);
                    create table flyway_schema_history (installed_rank int primary key, version varchar(50));
                    create table "weird""name" (id int primary key);
                    insert into items (name, data, tags, password_hash) values
                      ('alpha', '{"k":1}', '{x,y}', 'hash-1'), ('beta', null, null, null), ('gamma', null, null, null);
                    insert into pairs values (1, 'x', 'first');
                    insert into logs values ('no key');
                    insert into flyway_schema_history values (1, '1');
                    """);
        } catch (java.sql.SQLException e) {
            throw new IllegalStateException(e);
        }
    }

    @DynamicPropertySource
    static void properties(DynamicPropertyRegistry registry) {
        registry.add("nineouting.admin.username", () -> USERNAME);
        registry.add("nineouting.admin.password-hash", () -> new BCryptPasswordEncoder().encode(PASSWORD));
        registry.add("nineouting.admin.session-secret", () -> "test-session-secret-0123456789-abcdef");
        registry.add("nineouting.admin.cookie-secure", () -> "false");
        registry.add("nineouting.admin.databases.test.url", POSTGRES::getJdbcUrl);
        registry.add("nineouting.admin.databases.test.username", POSTGRES::getUsername);
        registry.add("nineouting.admin.databases.test.password", POSTGRES::getPassword);
    }

    @BeforeEach
    void resetLoginGuard() {
        guard.succeeded();
    }

    @Test
    void 로그인하지_않으면_막고_틀린_비밀번호는_실패한다() throws Exception {
        mockMvc.perform(get("/api/admin/databases")).andExpect(status().isUnauthorized());
        mockMvc.perform(write(post("/api/admin/session")).content(login("tester", "wrong")))
                .andExpect(status().isUnauthorized())
                .andExpect(jsonPath("$.code").value("LOGIN_FAILED"));
        mockMvc.perform(get("/api/admin/databases").cookie(new Cookie(AuthInterceptor.COOKIE, "forged.token")))
                .andExpect(status().isUnauthorized());
    }

    @Test
    void 로그인하면_쿠키로_DB와_표를_본다() throws Exception {
        Cookie cookie = loggedIn();
        mockMvc.perform(get("/api/admin/session").cookie(cookie)).andExpect(jsonPath("$.username").value(USERNAME));
        mockMvc.perform(get("/api/admin/databases").cookie(cookie))
                .andExpect(jsonPath("$[0].name").value("test"))
                .andExpect(jsonPath("$[0].database").value(POSTGRES.getDatabaseName()));
        mockMvc.perform(get("/api/admin/databases/test/tables").cookie(cookie))
                .andExpect(jsonPath("$[*].name", hasItem("items")));
        mockMvc.perform(get("/api/admin/databases/test/tables/items").cookie(cookie))
                .andExpect(jsonPath("$.primaryKey", contains("id")))
                .andExpect(jsonPath("$.readOnly").value(false))
                .andExpect(jsonPath("$.columns[?(@.name == 'data')].type").value("jsonb"));
    }

    @Test
    void 쪽_나누기_정렬_검색() throws Exception {
        Cookie cookie = loggedIn();
        mockMvc.perform(get("/api/admin/databases/test/tables/items/rows?size=2&sort=name&direction=desc").cookie(cookie))
                .andExpect(jsonPath("$.total").value(3))
                .andExpect(jsonPath("$.rows.length()").value(2))
                .andExpect(jsonPath("$.rows[0].name").value("gamma"));
        mockMvc.perform(get("/api/admin/databases/test/tables/items/rows?column=name&q=ALP").cookie(cookie))
                .andExpect(jsonPath("$.total").value(1))
                .andExpect(jsonPath("$.rows[0].data").value("{\"k\": 1}"))
                .andExpect(jsonPath("$.rows[0].tags").value("{x,y}"));
        // 열을 고르지 않으면 모든 열에서 찾는다
        mockMvc.perform(get("/api/admin/databases/test/tables/items/rows?q=hash-1").cookie(cookie))
                .andExpect(jsonPath("$.total").value(1));
    }

    @Test
    void 한_행을_추가하고_고치고_지운다() throws Exception {
        Cookie cookie = loggedIn();
        String id = com.jayway.jsonpath.JsonPath.read(mockMvc.perform(write(post("/api/admin/databases/test/tables/items/rows"))
                        .cookie(cookie).content("{\"values\":{\"name\":\"delta\",\"data\":\"{\\\"a\\\":true}\",\"tags\":\"{p}\"}}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.created_at").isNotEmpty())
                .andReturn().getResponse().getContentAsString(), "$.id");

        mockMvc.perform(write(put("/api/admin/databases/test/tables/items/rows")).cookie(cookie)
                        .content("{\"key\":{\"id\":\"" + id + "\"},\"values\":{\"name\":\"delta2\",\"data\":null}}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.name").value("delta2"))
                .andExpect(jsonPath("$.data").doesNotExist());

        mockMvc.perform(write(post("/api/admin/databases/test/tables/items/rows/delete")).cookie(cookie)
                        .content("{\"key\":{\"id\":\"" + id + "\"}}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.name").value("delta2"));
        mockMvc.perform(write(post("/api/admin/databases/test/tables/items/rows/delete")).cookie(cookie)
                        .content("{\"key\":{\"id\":\"" + id + "\"}}"))
                .andExpect(status().isNotFound());
    }

    @Test
    void 기본_키가_여러_열인_표도_고친다() throws Exception {
        Cookie cookie = loggedIn();
        mockMvc.perform(write(put("/api/admin/databases/test/tables/pairs/rows")).cookie(cookie)
                        .content("{\"key\":{\"a\":\"1\",\"b\":\"x\"},\"values\":{\"note\":\"changed\"}}"))
                .andExpect(jsonPath("$.note").value("changed"));
        // 기본 키 일부만 주면 여러 행이 바뀔 수 있어 막는다
        mockMvc.perform(write(put("/api/admin/databases/test/tables/pairs/rows")).cookie(cookie)
                        .content("{\"key\":{\"a\":\"1\"},\"values\":{\"note\":\"x\"}}"))
                .andExpect(status().isBadRequest());
    }

    @Test
    void 막아야_할_요청() throws Exception {
        Cookie cookie = loggedIn();
        // 배포 이력 표, 기본 키 없는 표는 읽기만
        mockMvc.perform(write(post("/api/admin/databases/test/tables/flyway_schema_history/rows/delete")).cookie(cookie)
                        .content("{\"key\":{\"installed_rank\":\"1\"}}"))
                .andExpect(status().isForbidden())
                .andExpect(jsonPath("$.code").value("READ_ONLY"));
        mockMvc.perform(write(post("/api/admin/databases/test/tables/logs/rows")).cookie(cookie)
                        .content("{\"values\":{\"message\":\"x\"}}"))
                .andExpect(status().isForbidden());
        // 없는 표, 없는 DB, 없는 열, SQL을 끼워 넣은 이름
        mockMvc.perform(get(java.net.URI.create("/api/admin/databases/test/tables/items%3Bdrop%20table%20items/rows")).cookie(cookie))
                .andExpect(status().isNotFound());
        mockMvc.perform(get("/api/admin/databases/nope/tables").cookie(cookie)).andExpect(status().isNotFound());
        mockMvc.perform(get("/api/admin/databases/test/tables/items/rows?sort=name;drop").cookie(cookie))
                .andExpect(status().isBadRequest());
        mockMvc.perform(write(post("/api/admin/databases/test/tables/items/rows")).cookie(cookie)
                        .content("{\"values\":{\"nope\":\"x\"}}"))
                .andExpect(status().isBadRequest());
        // 형식이 틀리거나 제약을 어기면 DB 메시지를 그대로
        mockMvc.perform(write(post("/api/admin/databases/test/tables/items/rows")).cookie(cookie)
                        .content("{\"values\":{\"name\":\"alpha\"}}"))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.code").value("DB_ERROR"));
        // 관리자 화면 머리글이 없는 쓰기 (다른 사이트에서 보낸 요청)
        mockMvc.perform(post("/api/admin/databases/test/tables/items/rows").cookie(cookie)
                        .contentType(MediaType.APPLICATION_JSON).content("{\"values\":{\"name\":\"z\"}}"))
                .andExpect(status().isForbidden());
        // 따옴표가 든 표 이름도 안전하게
        mockMvc.perform(get("/api/admin/databases/test/tables/{table}/rows", "weird\"name").cookie(cookie))
                .andExpect(status().isOk());
        assertThat(rowCount()).isEqualTo(3);
    }

    @Test
    void 다섯_번_틀리면_잠긴다() throws Exception {
        for (int i = 0; i < 5; i++) {
            mockMvc.perform(write(post("/api/admin/session")).content(login(USERNAME, "wrong")))
                    .andExpect(status().isUnauthorized());
        }
        mockMvc.perform(write(post("/api/admin/session")).content(login(USERNAME, PASSWORD)))
                .andExpect(status().isTooManyRequests())
                .andExpect(jsonPath("$.code").value("LOGIN_LOCKED"));
    }

    @Test
    void 로그아웃하면_쿠키를_지운다() throws Exception {
        mockMvc.perform(write(delete("/api/admin/session")).cookie(loggedIn()))
                .andExpect(status().isNoContent())
                .andExpect(header().string("Set-Cookie", org.hamcrest.Matchers.containsString("Max-Age=0")));
    }

    private Cookie loggedIn() throws Exception {
        return mockMvc.perform(write(post("/api/admin/session")).content(login(USERNAME, PASSWORD)))
                .andExpect(status().isOk())
                .andExpect(header().string("Set-Cookie", org.hamcrest.Matchers.containsString("HttpOnly")))
                .andReturn().getResponse().getCookie(AuthInterceptor.COOKIE);
    }

    private static String login(String username, String password) {
        return "{\"username\":\"" + username + "\",\"password\":\"" + password + "\"}";
    }

    private static MockHttpServletRequestBuilder write(MockHttpServletRequestBuilder request) {
        return request.header(AuthInterceptor.REQUEST_HEADER, AuthInterceptor.REQUEST_HEADER_VALUE)
                .contentType(MediaType.APPLICATION_JSON);
    }

    private static int rowCount() throws Exception {
        try (Connection connection = DriverManager.getConnection(POSTGRES.getJdbcUrl(), POSTGRES.getUsername(),
                POSTGRES.getPassword()); Statement sql = connection.createStatement();
             var rs = sql.executeQuery("select count(*) from items")) {
            rs.next();
            return rs.getInt(1);
        }
    }
}
